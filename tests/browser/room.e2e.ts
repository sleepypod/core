import { test, expect } from './ownerTest'
import { roomBroker } from './roomBroker'

test('room mapping is authenticated, versioned, initially disabled and does not invent connected sensors', async ({ page, request, playwright }, testInfo) => {
  const headers = { Authorization: `Bearer ${process.env.SLEEPYPOD_AUTH_TOKEN}` }
  const anonymous = await playwright.request.newContext({ baseURL: 'http://127.0.0.1:3218', storageState: { cookies: [], origins: [] } })
  for (const path of ['/api/v1/home/context', '/api/v1/home/context/history', '/api/v1/home/context/publisher', '/api/trpc/roomContext.status?input=%7B%22json%22%3A%7B%7D%7D']) expect((await anonymous.get(path)).status()).toBe(401)
  expect((await anonymous.put('/api/v1/home/context/configuration', { data: {} })).status()).toBe(401)
  expect((await anonymous.post('/api/trpc/roomContext.configure', { data: { json: {} } })).status()).toBe(401)
  await anonymous.dispose()
  const initial = await (await request.get('/api/v1/home/context', { headers })).json()
  expect(initial).toMatchObject({ apiVersion: 1, revision: 0, config: { enabled: false, mappings: [] }, connected: false, observations: [] })
  await page.goto('/en/home')
  await page.getByText('Existing single-source MQTT mappings', { exact: true }).click()
  await expect(page.getByText(/No room sensors mapped/)).toBeVisible()
  await page.getByText('Sensor mapping and setup', { exact: true }).click()
  await page.getByRole('checkbox', { name: 'Map room temperature' }).check()
  await page.getByLabel('Entity ID', { exact: true }).fill('sensor.fixture_bedroom')
  await page.getByLabel('Measurement timestamp attribute').fill('sample_time')
  await page.getByRole('button', { name: 'Save room sensors' }).click()
  await expect(page.getByText('Home Assistant publisher · revision 1')).toBeVisible()
  await expect(page.getByText('Input disabled', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Generate sensor publishers' })).toBeDisabled()
  const saved = await (await request.get('/api/v1/home/context', { headers })).json()
  expect(saved).toMatchObject({ revision: 1, config: { enabled: false }, observations: [{ status: 'disabled', value: null }] })
  expect((await request.put('/api/v1/home/context/configuration', { headers, data: { expectedRevision: 0, config: saved.config } })).status()).toBe(409)
  expect((await request.put('/api/v1/home/context/configuration', { headers, data: { expectedRevision: 1, config: { ...saved.config, mappings: [{ ...saved.config.mappings[0], unit: '%' }] } } })).status()).toBe(400)
  await page.screenshot({ path: testInfo.outputPath('room-desktop.png'), animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: testInfo.outputPath('room-phone.png'), animations: 'disabled' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('checkbox', { name: 'Accept mapped room measurements' }).check()
  await page.getByRole('button', { name: 'Save room sensors' }).click()
  await expect(page.getByText('Broker disconnected', { exact: true })).toBeVisible()
  await expect(page.getByText('Home Assistant publisher · revision 2')).toBeVisible()
  await page.reload()
  await page.getByText('Existing single-source MQTT mappings', { exact: true }).click()
  await expect(page.getByText('Broker disconnected', { exact: true })).toBeVisible()
  expect(await (await request.get('/api/v1/home/context/history', { headers })).json()).toMatchObject({ items: [] })
  const broker = await roomBroker()
  try {
    expect((await request.patch('/api/mqtt/settings', { headers, data: { enabled: true, url: broker.url, username: null, password: null, tlsEnabled: false, haDiscovery: false } })).ok()).toBe(true)
    await expect.poll(async () => (await (await request.get('/api/v1/home/context', { headers })).json()).connected).toBe(true)
    const sample = { schemaVersion: 1, source: 'home_assistant', revision: 2, metric: 'temperature', entityId: 'sensor.fixture_bedroom', unit: '°C', available: true, value: 20, measuredAt: Date.now() - 1000, reportedAt: Date.now() }
    broker.publish(sample)
    await expect(page.getByText('Fresh measurement', { exact: true })).toBeVisible({ timeout: 12000 })
    const observed = await (await request.get('/api/v1/home/context', { headers })).json()
    expect(observed.observations[0]).toMatchObject({ value: 68, measuredAt: sample.measuredAt, status: 'fresh' })
    const generated = await (await request.get('/api/v1/home/context/publisher', { headers })).json()
    expect(generated.revision).toBe(2)
    expect(JSON.parse(generated.automations[0]).actions[0].data).toMatchObject({ retain: false, topic: observed.topic })
    await page.screenshot({ path: testInfo.outputPath('room-phone-live.png'), animations: 'disabled' })
    await page.emulateMedia({ colorScheme: 'dark' })
    await expect(page.getByText('Fresh measurement', { exact: true })).toHaveCSS('color', 'rgb(139, 139, 146)')
    await page.screenshot({ path: testInfo.outputPath('room-phone-dark.png'), animations: 'disabled' })
    broker.publish({ ...sample, reportedAt: Date.now(), available: false, value: null, measuredAt: null })
    await expect(page.getByText('Sensor unavailable', { exact: true })).toBeVisible({ timeout: 12000 })
    expect((await (await request.get('/api/v1/home/context', { headers })).json()).observations[0].value).toBeNull()
    expect((await (await request.get('/api/v1/home/context/history', { headers })).json()).items).toHaveLength(2)
  }
  finally {
    await request.patch('/api/mqtt/settings', { headers, data: { enabled: false, url: null } })
    await broker.close()
  }
  await expect(page.getByText('Broker disconnected', { exact: true })).toBeVisible({ timeout: 12000 })
  await request.put('/api/v1/home/context/configuration', { headers, data: { expectedRevision: 2, config: { ...saved.config, enabled: false } } })
})

test('room drafts survive a failed refresh and a conflicting change from another owner client', async ({ page, request }) => {
  const headers = { Authorization: `Bearer ${process.env.SLEEPYPOD_AUTH_TOKEN}` }
  const initial = await (await request.get('/api/v1/home/context', { headers })).json()
  await page.goto('/en/home')
  await page.getByText('Existing single-source MQTT mappings', { exact: true }).click()
  await page.getByText('Sensor mapping and setup', { exact: true }).click()
  await page.getByLabel('Room name', { exact: true }).fill('Unsaved bedroom draft')
  const statusPath = /\/api\/trpc\/[^?]*roomContext.status/
  await page.route(statusPath, route => route.abort())
  await expect(page.getByText(/Room data could not be refreshed/)).toBeVisible({ timeout: 12000 })
  await expect(page.getByLabel('Room name', { exact: true })).toHaveValue('Unsaved bedroom draft')
  await request.put('/api/v1/home/context/configuration', { headers, data: { expectedRevision: initial.revision, config: { ...initial.config, roomName: 'Another owner client' } } })
  await page.unroute(statusPath)
  await page.getByRole('alert').filter({ hasText: /^Room data could not be refreshed\. Readings are withheld\./ }).getByRole('button', { name: 'Retry', exact: true }).click()
  await expect(page.getByText(/The stored mapping changed/)).toBeVisible()
  await expect(page.getByLabel('Room name', { exact: true })).toHaveValue('Unsaved bedroom draft')
  await page.getByRole('button', { name: 'Save room sensors' }).click()
  await expect(page.getByRole('alert').filter({ hasText: 'Room configuration changed' })).toBeVisible()
  await page.getByRole('button', { name: 'Discard draft and reload' }).click()
  await expect(page.getByLabel('Room name', { exact: true })).toHaveValue('Another owner client')
  await request.put('/api/v1/home/context/configuration', { headers, data: { expectedRevision: initial.revision + 1, config: initial.config } })
})
