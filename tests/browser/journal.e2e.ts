import { test, expect } from './ownerTest'

const fields = { restfulness: 4, comfort: 'warm', caffeine: true, alcohol: false, exercise: true, notes: 'Synthetic private journal note' }
const headers = () => ({ Authorization: `Bearer ${process.env.SLEEPYPOD_AUTH_TOKEN}` })

test('journal REST protects private data and rejects stale revisions, including after removal', async ({ request, playwright }) => {
  const anonymous = await playwright.request.newContext({ baseURL: 'http://127.0.0.1:3218', storageState: { cookies: [], origins: [] } })
  expect((await anonymous.get('/api/v1/journal?side=left')).status()).toBe(401)
  expect((await anonymous.post('/api/v1/journal', { data: { side: 'left', date: '2025-01-01', fields, expectedRevision: null } })).status()).toBe(401)
  expect((await anonymous.get('/api/trpc/journal.get?input=%7B%22json%22%3A%7B%22side%22%3A%22left%22%7D%7D')).status()).toBe(401)
  expect((await anonymous.post('/api/v1/comfort/mode', { data: { side: 'left', mode: 'preview' } })).status()).toBe(401)
  await anonymous.dispose()
  const url = '/api/v1/journal?side=left&date=2025-01-01'
  const before = await request.get(url, { headers: headers() })
  expect(before.headers()['cache-control']).toContain('no-store')
  expect((await before.json()).selected.record).toBeNull()
  const input = { side: 'left', date: '2025-01-01', expectedRevision: null, fields }
  const saved = await request.post('/api/v1/journal', { headers: headers(), data: input })
  expect(saved.status()).toBe(200)
  expect(saved.headers()['cache-control']).toContain('no-store')
  const record = await saved.json()
  expect(record.record.fields).toEqual(fields)
  expect((await request.post('/api/v1/journal', { headers: headers(), data: input })).status()).toBe(409)
  expect((await request.post('/api/v1/journal', { headers: headers(), data: { ...input, expectedRevision: record.revision, fields: null } })).status()).toBe(200)
  expect((await request.post('/api/v1/journal', { headers: headers(), data: { ...input, expectedRevision: record.revision } })).status()).toBe(409)
  const removed = await (await request.get(url, { headers: headers() })).json()
  expect(removed.selected).toMatchObject({ record: null })
  expect(removed.selected.revision).not.toBe(record.revision)
  expect(removed.entries).toEqual([])
  expect((await request.post('/api/v1/comfort/mode', { headers: headers(), data: { side: 'left', mode: 'active' } })).status()).toBe(412)
})

test('morning journal retains drafts and resolves conflicts on desktop and phone', async ({ page, request }, testInfo) => {
  await page.goto('/en/sleep?view=journal')
  const notes = page.getByLabel('Private notes', { exact: true })
  await expect(notes).toBeVisible()
  const date = await page.getByLabel('Wake date', { exact: true }).inputValue()
  await notes.fill('My unsaved left-side draft')
  await page.getByRole('tab', { name: 'Right side', exact: true }).click()
  await expect(notes).toHaveValue('')
  await notes.fill('My unsaved right-side draft')
  await page.getByRole('tab', { name: 'Left side', exact: true }).click()
  await expect(notes).toHaveValue('My unsaved left-side draft')
  await page.getByLabel('Restfulness', { exact: true }).selectOption('5')
  await page.getByLabel('Temperature comfort', { exact: true }).selectOption('cold')
  await page.getByLabel(/caffeine.*during the previous day/i).check()
  await page.getByRole('button', { name: 'Save check-in', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Morning check-in' }).getByRole('status')).toContainText('saved on your Pod')
  const url = `/api/v1/journal?side=left&date=${date}`
  const saved = await (await request.get(url, { headers: headers() })).json()
  expect(saved.selected.record.fields).toMatchObject({ notes: 'My unsaved left-side draft', restfulness: 5, comfort: 'cold', caffeine: true })
  await notes.fill('Keep this local edit after a conflict')
  expect((await request.post('/api/v1/journal', { headers: headers(), data: { side: 'left', date, expectedRevision: saved.selected.revision,
    fields: { ...fields, notes: 'A newer edit from another device' } } })).status()).toBe(200)
  await page.getByRole('button', { name: 'Save check-in', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Morning check-in' }).getByRole('status')).toContainText('Save not confirmed')
  await expect(notes).toHaveValue('Keep this local edit after a conflict')
  await page.getByRole('button', { name: 'Refresh saved entry', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: 'The saved entry changed' })).toBeVisible()
  await page.getByText('Compare saved entry', { exact: true }).click()
  await expect(page.getByText('A newer edit from another device', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Keep my draft for this revision', exact: true }).click()
  await page.getByRole('button', { name: 'Save check-in', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Morning check-in' }).getByRole('status')).toContainText('saved on your Pod')
  expect((await (await request.get(url, { headers: headers() })).json()).selected.record.fields.notes).toBe('Keep this local edit after a conflict')
  await page.screenshot({ path: testInfo.outputPath('journal-desktop.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: testInfo.outputPath('journal-mobile.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Remove check-in', exact: true }).click()
  const removalVersion = await (await request.get(url, { headers: headers() })).json()
  expect((await request.post('/api/v1/journal', { headers: headers(), data: { side: 'left', date,
    expectedRevision: removalVersion.selected.revision, fields: { ...fields, notes: 'Changed after opening the removal dialog' } } })).status()).toBe(200)
  await page.getByRole('button', { name: 'Refresh saved entry', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Confirm removal', exact: true })).toBeDisabled()
  await expect(page.getByText('The saved entry changed after removal was requested. Cancel and review it first.')).toBeVisible()
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('button', { name: 'Remove check-in', exact: true }).click()
  await page.getByRole('button', { name: 'Confirm removal', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Morning check-in' }).getByRole('status')).toContainText('Check-in removed')
  await expect(notes).toHaveValue('')
  await page.reload()
  await expect(notes).toHaveValue('')
  expect((await (await request.get(url, { headers: headers() })).json()).selected.record).toBeNull()
})

test('an uncertain network response retains the draft and reconciles the saved revision', async ({ page, request }) => {
  await page.goto('/en/sleep?view=journal')
  await page.getByLabel('Wake date', { exact: true }).fill('2025-06-01')
  const notes = page.getByLabel('Private notes', { exact: true })
  await expect(page.getByRole('region', { name: 'Morning check-in' })).toContainText('2025-06-01')
  await notes.fill('A draft whose response was lost')
  await page.route('**/api/trpc/journal.save**', async (route) => {
    // The server commits, but the browser never receives its acknowledgment.
    await route.fetch()
    await route.abort('failed')
  }, { times: 1 })
  await page.getByRole('button', { name: 'Save check-in', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Morning check-in' }).getByRole('status')).toContainText('Save not confirmed')
  await expect(notes).toHaveValue('A draft whose response was lost')
  const saved = await (await request.get('/api/v1/journal?side=left&date=2025-06-01', { headers: headers() })).json()
  expect(saved.selected.record.fields.notes).toBe('A draft whose response was lost')
  await page.getByRole('button', { name: 'Refresh saved entry', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Save check-in', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Use saved entry', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Morning check-in' }).getByRole('status')).toHaveText('Saved entry loaded.')
  expect((await (await request.get('/api/v1/journal?side=left&date=2025-06-01', { headers: headers() })).json()).selected.revision).toBe(saved.selected.revision)
})
