import { expect, test, type Page } from '@playwright/test'
import { mockPersonal } from './personal-fixture'
import { test as ownerTest } from './ownerTest'

async function capturePractice(page: Page, name: string) {
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: test.info().outputPath(name), fullPage: true })
}

test('personal practice teaches temperature, one alarm and both Stops without live writes', async ({ page }) => {
  const account = await mockPersonal(page)
  await page.goto('/household/index.html')
  await page.getByRole('button', { name: 'Start practice' }).click()
  const practice = page.getByRole('region', { name: 'Practice the bed controls' })
  await expect(page.getByLabel('Manual hold')).not.toBeVisible()
  await expect(practice).toContainText('Your bed and real alarms stay unchanged')
  await capturePractice(page, 'practice-desktop-temperature.png')
  await practice.getByRole('button', { name: '1°F cooler' }).click()
  await expect(practice.getByRole('status')).toContainText('not requested yet')
  await practice.getByRole('button', { name: 'Apply my target' }).click()
  await expect(practice.getByRole('img')).toHaveAttribute('aria-label', /75 degrees/)
  await practice.getByRole('button', { name: 'Next lesson' }).click()
  await expect(practice.getByRole('heading', { name: 'Give tomorrow a later start.' })).toBeFocused()
  await expect(practice.getByRole('heading', { name: 'Give tomorrow a later start.' })).toBeInViewport()
  await practice.getByLabel('Tomorrow’s practice wake time').fill('09:00')
  await practice.getByRole('button', { name: 'Review practice alarm' }).click()
  await expect(practice).toContainText('08:30')
  await expect(practice).toContainText('Still 07:00')
  await page.setViewportSize({ width: 1024, height: 1366 })
  await capturePractice(page, 'practice-tablet-alarm-review.png')
  await practice.getByRole('button', { name: 'Save practice alarm' }).click()
  await practice.getByRole('button', { name: 'Next lesson' }).click()
  await practice.getByRole('button', { name: 'Stop temperature' }).click()
  await expect(practice.getByText('Playing', { exact: true })).toBeVisible()
  await practice.getByRole('button', { name: 'Stop vibration' }).click()
  await expect(practice).toContainText('09:00 · still saved')
  await expect(practice).toContainText('3 of 3 actions practiced')
  await capturePractice(page, 'practice-tablet-complete.png')
  await practice.getByRole('button', { name: 'Finish practice' }).click()
  await expect(page.getByRole('button', { name: 'Start practice' })).toBeFocused()
  await expect(page.getByRole('button', { name: 'Apply my target', exact: true })).toBeVisible()
  expect(account.posts).toEqual([])
  expect(account.unexpected).toEqual([])
  await page.getByRole('button', { name: 'Start practice' }).click()
  await expect(practice).toContainText('0 of 3 actions practiced')
  await expect(practice.getByRole('img')).toHaveAttribute('aria-label', /76 degrees/)
})

test('phone practice stays readable, allows skipping and resets without changing the account', async ({ page }) => {
  const account = await mockPersonal(page)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ colorScheme: 'dark', reducedMotion: 'reduce' })
  await page.goto('/household/index.html')
  await page.getByRole('button', { name: 'Start practice' }).click()
  await page.addStyleTag({ content: ':root{font-size:24px}' })
  const practice = page.getByRole('region', { name: 'Practice the bed controls' })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await capturePractice(page, 'practice-phone-temperature-dark-large.png')
  await practice.getByRole('button', { name: 'Skip to next lesson' }).click()
  await expect(practice.getByRole('heading', { name: 'Give tomorrow a later start.' })).toBeInViewport()
  await practice.getByRole('button', { name: 'Review practice alarm' }).click()
  await practice.getByLabel('Tomorrow’s practice wake time').fill('')
  await expect(practice.getByRole('button', { name: 'Save practice alarm' })).not.toBeVisible()
  await expect(practice.getByRole('button', { name: 'Review practice alarm' })).toBeDisabled()
  await capturePractice(page, 'practice-phone-invalid-alarm-dark-large.png')
  await practice.getByRole('button', { name: 'Stop an action' }).click()
  await practice.getByRole('button', { name: 'Stop vibration' }).click()
  await expect(practice.getByText('On', { exact: true })).toBeVisible()
  await capturePractice(page, 'practice-phone-separate-stops-dark-large.png')
  await practice.getByRole('button', { name: 'Restart practice' }).click()
  await expect(practice).toContainText('0 of 3 actions practiced')
  await practice.getByRole('button', { name: 'Leave practice' }).click()
  await expect(page.getByRole('button', { name: 'Start practice' })).toBeFocused()
  expect(account.posts).toEqual([])
})

ownerTest('owner settings opens the same lessons and returns to the connection section', async ({ page }) => {
  await page.goto('/en/settings?section=connection')
  await page.getByRole('link', { name: 'Practice temperature, alarms and Stop' }).click()
  await expect(page).toHaveURL(/\/en\/practice$/)
  const practice = page.getByRole('region', { name: 'Practice the bed controls' })
  await expect(practice).toBeVisible()
  await capturePractice(page, 'practice-owner-desktop.png')
  await practice.getByRole('button', { name: '1°F cooler' }).click()
  await expect(practice.getByRole('img')).toHaveAttribute('aria-label', /requested target 75 degrees/)
  await expect(practice.getByRole('button', { name: /Apply/ })).toHaveCount(0)
  await capturePractice(page, 'practice-owner-requested.png')
  await practice.getByRole('button', { name: 'Stop an action' }).click()
  await practice.getByRole('button', { name: 'Turn off' }).click()
  await expect(practice.getByText('Off', { exact: true })).toBeVisible()
  await expect(practice.getByText('Playing', { exact: true })).toBeVisible()
  await capturePractice(page, 'practice-owner-power-off.png')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ colorScheme: 'dark', reducedMotion: 'reduce' })
  await page.addStyleTag({ content: ':root{font-size:24px}' })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await capturePractice(page, 'practice-owner-power-off-phone-dark-large.png')
  await practice.getByRole('button', { name: 'Leave practice' }).click()
  await expect(page).toHaveURL(/\/en\/settings\?section=connection$/)
})

test('practice can apply a target and advance using the keyboard', async ({ page }) => {
  const account = await mockPersonal(page)
  await page.goto('/household/index.html')
  await page.getByRole('button', { name: 'Start practice' }).focus()
  await page.keyboard.press('Enter')
  const practice = page.getByRole('region', { name: 'Practice the bed controls' })
  await expect(practice.getByRole('heading', { name: 'Try a cooler target.' })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(practice.getByRole('button', { name: '1°F cooler' })).toBeFocused()
  await page.keyboard.press('Enter')
  await page.keyboard.press('Tab')
  await page.keyboard.press('Tab')
  await expect(practice.getByRole('button', { name: 'Apply my target' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(practice.getByRole('img')).toHaveAttribute('aria-label', /75 degrees/)
  await page.keyboard.press('Tab')
  await expect(practice.getByRole('button', { name: 'Next lesson' })).toBeFocused()
  await capturePractice(page, 'practice-keyboard-applied.png')
  await page.keyboard.press('Enter')
  await expect(practice.getByRole('heading', { name: 'Give tomorrow a later start.' })).toBeFocused()
  expect(account.posts).toEqual([])
})
