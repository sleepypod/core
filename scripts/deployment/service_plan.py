#!/usr/bin/env python3
"""Render isolated Pod services for review; never install, enable or start them."""
import argparse
import hashlib
import json
from pathlib import Path
import re

from prepare_offline import NODE_VERSION

MODULES = ('piezo-processor', 'sleep-detector', 'environment-monitor', 'calibrator')
LEGACY_UNITS = ('free-sleep.service', 'free-sleep-stream.service')
CORE_UNIT = 'sleepypod.service'
CORE_UNITS = (CORE_UNIT,) + tuple('sleepypod-' + name + '.service' for name in MODULES)
PLAN_FORMAT = 'sleepypod-service-plan/1'
MAINTENANCE_SOCKET = '/run/sleepypod-maintenance/control.sock'


def pod_path(value):
    """Avoid systemd expansion, line injection and accidental use of shared roots."""
    if not isinstance(value, str) or not re.fullmatch(r'/[A-Za-z0-9_./-]+', value):
        raise ValueError('Use an absolute Pod path without whitespace or expansion characters')
    path = Path(value)
    if '..' in path.parts or str(path) != value or value == '/':
        raise ValueError('Use a canonical non-root Pod path')
    return value


def validate_config(config):
    required = {'release', 'modules', 'data', 'environment', 'dacSocket', 'rawData'}
    if not isinstance(config, dict) or set(config) not in (required, required | {'maintenanceSocket'}):
        raise ValueError('Unexpected service configuration fields')
    if 'maintenanceSocket' in config and config['maintenanceSocket'] != MAINTENANCE_SOCKET:
        raise ValueError('Use the fixed private maintenance socket')
    for value in config.values():
        pod_path(value)
    # Never let a new runtime or database overwrite the retained controller.
    for name in ('release', 'modules', 'data', 'environment'):
        if not config[name].startswith('/persistent/sleepypod-unified/'):
            raise ValueError('Managed paths must be beneath /persistent/sleepypod-unified/')
    directories = [Path(config[name]) for name in ('release', 'modules', 'data')]
    for index, directory in enumerate(directories):
        for other in directories[index + 1:]:
            if directory == other or directory in other.parents or other in directory.parents:
                raise ValueError('Release, modules and data must be separate directories')
    environment = Path(config['environment'])
    if any(environment == directory or directory in environment.parents for directory in directories):
        raise ValueError('Keep the credential environment outside source and data directories')
    if not config['dacSocket'].endswith('/dac.sock'):
        raise ValueError('Expected an explicitly inspected dac.sock path')
    return config


def render(config):
    """Use the existing dac account and exact private paths, without global runtime changes."""
    validate_config(config)
    release, modules, data = (config[name] for name in ('release', 'modules', 'data'))
    maintenance = f'Environment="SLEEPYPOD_MAINTENANCE_SOCKET={MAINTENANCE_SOCKET}"\n' if 'maintenanceSocket' in config else ''
    shared = f'''User=dac
Group=dac
UMask=0077
Environment="DATABASE_URL=file:{data}/sleepypod.db"
Environment="BIOMETRICS_DATABASE_URL=file:{data}/biometrics.db"
Environment="RAW_DATA_DIR={config['rawData']}"
Environment="CALIBRATION_TRIGGER_PATH={data}/.calibrate-trigger"
Environment="SLEEP_DETECTOR_STATE_PATH={data}/sleep-detector-state.json"
Environment="PYTHONDONTWRITEBYTECODE=1"
Environment="PYTHONNOUSERSITE=1"
Environment="OPENBLAS_NUM_THREADS=1"
Environment="OMP_NUM_THREADS=1"
Restart=on-failure
RestartSec=10
TimeoutStopSec=30
KillMode=control-group
NoNewPrivileges=true
PrivateTmp=true
ProtectSystem=strict
ProtectHome=read-only
ProtectKernelTunables=true
ReadWritePaths={data}
'''
    core = f'''# Generated by scripts/deployment/service_plan.py. Review before installation.
[Unit]
Description=SleepyPod unified controller (isolated runtime)
After=network.target nats-server.service {' '.join(LEGACY_UNITS)}
Conflicts={' '.join(LEGACY_UNITS)}
Wants={' '.join(CORE_UNITS[1:])}
RequiresMountsFor={release} {data}

[Service]
Type=simple
{shared}WorkingDirectory={release}/app
EnvironmentFile={config['environment']}
{maintenance}Environment="NODE_ENV=production"
Environment="HOSTNAME=0.0.0.0"
Environment="PORT=3000"
Environment="PIEZO_WS_PORT=3001"
Environment="PIEZO_SENSOR_SOURCE=nats"
Environment="DAC_SOCK_PATH={config['dacSocket']}"
Environment="HOMEKIT_DIR={data}/homekit"
Environment="EXPORT_STAGING_DIR={data}/export-staging"
Environment="PATH={release}/runtime/node-v{NODE_VERSION}-linux-arm64/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin"
ReadWritePaths={Path(config['dacSocket']).parent}
ExecStart={release}/runtime/node-v{NODE_VERSION}-linux-arm64/bin/node {release}/app/server.js
MemoryMax=1536M

[Install]
WantedBy=multi-user.target
'''
    units = {CORE_UNIT: core}
    for name in MODULES:
        units['sleepypod-' + name + '.service'] = f'''# Generated by scripts/deployment/service_plan.py. Review before installation.
[Unit]
Description=SleepyPod {name} (isolated data)
After=sleepypod.service nats-server.service {' '.join(LEGACY_UNITS)}
BindsTo=sleepypod.service
PartOf=sleepypod.service
Conflicts={' '.join(LEGACY_UNITS)}
RequiresMountsFor={modules} {data}

[Service]
Type=simple
{shared}WorkingDirectory={modules}/{name}
Environment="MPLCONFIGDIR=/tmp/sleepypod-matplotlib"
ExecStart={modules}/{name}/.venv/bin/python {modules}/{name}/main.py
MemoryMax={'1024M' if name == 'calibrator' else '256M'}
CPUQuota={'25%' if name == 'calibrator' else '50%'}

[Install]
WantedBy=multi-user.target
'''
    return units


def prepare(config, output):
    units = render(config)
    if output.exists() or output.is_symlink():
        raise ValueError('Output must be a new directory')
    output.mkdir(mode=0o700)
    for name, content in units.items():
        target = output / name
        target.write_text(content)
        target.chmod(0o600)
    manifest = {'format': PLAN_FORMAT, 'config': config,
                'units': {name: hashlib.sha256(content.encode()).hexdigest() for name, content in units.items()},
                'servicesStarted': False, 'bootSelectionChanged': False}
    (output / 'plan.json').write_text(json.dumps(manifest, indent=2) + '\n')
    (output / 'plan.json').chmod(0o600)
    return manifest


def read_plan(directory):
    if (directory / 'plan.json').is_symlink():
        raise ValueError('Plan must be a regular file')
    plan = json.loads((directory / 'plan.json').read_text())
    if plan.get('format') != PLAN_FORMAT:
        raise ValueError('Unsupported service plan')
    expected = render(plan['config'])
    if set(plan.get('units', {})) != set(expected):
        raise ValueError('Unexpected service membership')
    for name, content in expected.items():
        target = directory / name
        if target.is_symlink() or target.read_text() != content:
            raise ValueError('Service differs from the reviewed template: ' + name)
        if hashlib.sha256(content.encode()).hexdigest() != plan['units'][name]:
            raise ValueError('Service checksum mismatch: ' + name)
    return plan


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--config', required=True, type=Path)
    parser.add_argument('--output', required=True, type=Path)
    args = parser.parse_args()
    prepare(json.loads(args.config.read_text()), args.output)
    print(json.dumps({'plan': str(args.output), 'servicesStarted': False}))


if __name__ == '__main__':
    main()
