import { cleanup, fireEvent, render, screen } from '@testing-library/react'
import { afterEach, expect, it, vi } from 'vitest'
import { ControlPractice } from './ControlPractice'

afterEach(() => {
  cleanup()
  vi.unstubAllGlobals()
  vi.restoreAllMocks()
})

it('teaches the three actions without requesting a controller or saving personal data', () => {
  const fetchRequest = vi.fn(), close = vi.fn()
  vi.stubGlobal('fetch', fetchRequest)
  const save = vi.spyOn(Storage.prototype, 'setItem')
  render(<ControlPractice onClose={close} />)
  fireEvent.click(screen.getByRole('button', { name: '1°F cooler' }))
  expect(screen.getByRole('status').textContent).toContain('not applied yet')
  expect(screen.getByRole('img').getAttribute('aria-label')).toContain('76 degrees')
  fireEvent.click(screen.getByRole('button', { name: 'Apply practice target' }))
  expect(screen.getByRole('img').getAttribute('aria-label')).toContain('75 degrees')
  fireEvent.click(screen.getByRole('button', { name: 'Next lesson' }))
  fireEvent.change(screen.getByLabelText('Tomorrow’s practice wake time'), { target: { value: '00:15' } })
  fireEvent.click(screen.getByRole('button', { name: 'Review practice alarm' }))
  expect(screen.getByText('23:45')).toBeTruthy()
  expect(screen.getByText('Still 07:00')).toBeTruthy()
  fireEvent.click(screen.getByRole('button', { name: 'Save practice alarm' }))
  expect(screen.getByRole('status').textContent).toContain('saved for 00:15')
  fireEvent.click(screen.getByRole('button', { name: 'Next lesson' }))
  fireEvent.click(screen.getByRole('button', { name: 'Stop practice temperature' }))
  expect(screen.getByText('Playing')).toBeTruthy()
  fireEvent.click(screen.getByRole('button', { name: 'Stop practice vibration' }))
  expect(screen.getByText('00:15 · still saved')).toBeTruthy()
  expect(screen.getByText(/3 of 3 actions practiced/)).toBeTruthy()
  fireEvent.click(screen.getByRole('button', { name: 'Finish practice' }))
  expect(close).toHaveBeenCalledOnce()
  expect(fetchRequest).not.toHaveBeenCalled()
  expect(save).not.toHaveBeenCalled()
})

it('withdraws a stale alarm review and resets example progress without blocking exit', () => {
  const close = vi.fn()
  render(<ControlPractice onClose={close} />)
  fireEvent.click(screen.getByRole('button', { name: 'Skip to next lesson' }))
  fireEvent.click(screen.getByRole('button', { name: 'Review practice alarm' }))
  fireEvent.change(screen.getByLabelText('Tomorrow’s practice wake time'), { target: { value: '' } })
  expect(screen.queryByRole('button', { name: 'Save practice alarm' })).toBeNull()
  expect((screen.getByRole('button', { name: 'Review practice alarm' }) as HTMLButtonElement).disabled).toBe(true)
  fireEvent.click(screen.getByRole('button', { name: 'Stop an action' }))
  fireEvent.click(screen.getByRole('button', { name: 'Stop practice vibration' }))
  fireEvent.click(screen.getByRole('button', { name: 'Restart practice' }))
  expect(screen.getByText('0 of 3 actions practiced.')).toBeTruthy()
  fireEvent.click(screen.getByRole('button', { name: 'Stop an action' }))
  expect(screen.getByText('Playing')).toBeTruthy()
  fireEvent.click(screen.getByRole('button', { name: 'Leave practice' }))
  expect(close).toHaveBeenCalledOnce()
})
